-- Schema for accounts, services and transactions. Idempotent: safe to run repeatedly.

BEGIN;

DO $$ BEGIN
  CREATE TYPE public.bonus_state AS ENUM ('locked', 'unlocked');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE public.payment_term AS ENUM ('hour', 'week', 'month', 'quarter_year', 'half_year', 'year');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE public.service_status AS ENUM ('active', 'blocked', 'deleted', 'suspended', 'prolong_wait');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE public.transaction_status AS ENUM ('performed', 'not_performed');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE public.transaction_type AS ENUM ('order', 'prolong');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS public.accounts (
  "id"               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "email"            text               NOT NULL UNIQUE,
  "balance"          bigint             NOT NULL DEFAULT 0 CHECK ("balance" >= 0),
  "withdrawBalance"  bigint             NOT NULL DEFAULT 0 CHECK ("withdrawBalance" >= 0),
  "totalReplenished" bigint             NOT NULL DEFAULT 0 CHECK ("totalReplenished" >= 0),
  "bonusBalance"     bigint             NOT NULL DEFAULT 0 CHECK ("bonusBalance" >= 0),
  "bonusState"       public.bonus_state NOT NULL DEFAULT 'locked'
);

CREATE TABLE IF NOT EXISTS public.services (
  "id"          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name"        text                  NOT NULL,
  "ownerId"     integer               NOT NULL REFERENCES public.accounts ("id"),
  "paymentTerm" public.payment_term   NOT NULL,
  "autoProlong" boolean               NOT NULL DEFAULT false,
  "createdAt"   timestamptz           NOT NULL DEFAULT now(),
  "expiresAt"   timestamptz           NOT NULL,
  "status"      public.service_status NOT NULL,
  "price"       bigint                NOT NULL CHECK ("price" >= 0),
  CHECK ("expiresAt" > "createdAt")
);

CREATE INDEX IF NOT EXISTS services_owner_id_idx ON public.services ("ownerId");

CREATE TABLE IF NOT EXISTS public.transactions (
  "id"          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "amount"      bigint                    NOT NULL CHECK ("amount" >= 0),
  "status"      public.transaction_status NOT NULL,
  "performedAt" timestamptz,
  "createdAt"   timestamptz               NOT NULL DEFAULT now(),
  "type"        public.transaction_type   NOT NULL,
  "serviceId"   integer                   NOT NULL REFERENCES public.services ("id"),
  CHECK (("status" = 'performed') = ("performedAt" IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS transactions_service_id_idx ON public.transactions ("serviceId");

COMMIT;
